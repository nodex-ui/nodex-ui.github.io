/** Turns a block slug such as "login-03" into the label people read, "Login 03". */
function labelFor(slug) {
  return slug.split("-").map((part) => part.charAt(0).toUpperCase() + part.slice(1)).join(" ");
}

/** One catalog entry: the block's file name, sidebar label, preview height and description. */
function block(name, label, height) {
  return { name, label, height, description: descriptions[name] };
}

